    #[test]
    fn every_corpus_sentence_detects_as_its_own_language() {
        // Ground truth: each sentence is written in the language named
        // beside it, and each abstention row is a documented dispatch rule
        // (the Arabic guard, an unsupported script, or no signal at all).
        // Nothing here is a recording of what the code emits.
        let d = HashedLinearDetector::new();
        for &(input, expected) in GOLDEN {
            let got = d.detect(input);
            match expected {
                None => assert_eq!(
                    got,
                    LanguageDetection::none(),
                    "expected abstention for {input:?}, got {got:?}"
                ),
                Some((language, _)) => {
                    let candidate = got
                        .best()
                        .unwrap_or_else(|| panic!("expected a candidate for {input:?}"));
                    assert_eq!(candidate.language, language, "wrong language for {input:?}");
                }
            }
        }
    }

    #[test]
    fn committed_weight_tables_have_not_changed() {
        // A change detector, not a specification. These bits are what the
        // committed weight tables produce; no publication predicts them.
        // A diff here means the model was retrained (fine, if deliberate
        // and documented) or the feature extraction drifted (not fine) —
        // and either way it must be read, not re-recorded.
        let d = HashedLinearDetector::new();
        for &(input, expected) in GOLDEN {
            let Some((_, confidence_bits)) = expected else {
                continue;
            };
            let got = d.detect(input);
            let candidate = got
                .best()
                .unwrap_or_else(|| panic!("expected a candidate for {input:?}"));
            assert_eq!(
                candidate.confidence.get().to_bits(),
                confidence_bits,
                "confidence drifted for {input:?}: {} (bits {:#010X})",
                candidate.confidence,
                candidate.confidence.get().to_bits()
            );
        }
    }

    #[test]
    fn detect_is_deterministic_and_bit_identical_across_repeated_calls() {
        // Stronger than WhatlangDetector's determinism test on purpose:
        // the module docs promise *bit* reproducibility, so compare
        // confidence bit patterns, not just PartialEq equality.
        let d = HashedLinearDetector::new();
        for &(input, _) in GOLDEN {
            let first = d.detect(input);
            for _ in 0..5 {
                let again = d.detect(input);
                assert_eq!(again, first, "detect({input:?}) not deterministic");
                assert_eq!(
                    again.best().map(|c| c.confidence.get().to_bits()),
                    first.best().map(|c| c.confidence.get().to_bits()),
                    "confidence bits drifted across calls for {input:?}"
                );
            }
        }
    }

